create table if not exists public.quote_requests (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  business text,
  phone text not null,
  email text not null,
  service text,
  budget text,
  message text not null,
  source text default 'website',
  status text not null default 'New'
);

alter table public.quote_requests enable row level security;

revoke all on table public.quote_requests from anon, authenticated;

grant insert on table public.quote_requests to anon;

drop policy if exists "Public can submit quote requests" on public.quote_requests;
create policy "Public can submit quote requests"
on public.quote_requests
for insert
to anon
with check (
  length(trim(name)) between 2 and 100
  and length(trim(phone)) between 5 and 40
  and length(trim(email)) between 5 and 254
  and length(trim(message)) between 5 and 5000
);

